import assert from "node:assert/strict";
import { canTouchRecord } from "../src/lib/record-access";
import { isReservedBookingSource } from "../src/lib/booking-policy";
import { taskCompletedAt } from "../src/lib/task-status";
import type { SessionUser } from "../src/lib/session";
const user = { id: "staff-a", branchId: "branch-a", accessMode: "BRANCH" } as SessionUser;
assert.equal(canTouchRecord(user, { branchId: "branch-a" }), true);
assert.equal(canTouchRecord(user, { branchId: "branch-b" }), false);
assert.equal(canTouchRecord(user, { branchId: null }), false, "Unscoped records must not bypass branch isolation");
assert.equal(canTouchRecord({ ...user, branchId: null }, { branchId: null }), false, "Unassigned branch managers must fail closed");
assert.equal(canTouchRecord({ ...user, accessMode: "ALL" }, { branchId: null }), true);
const assigned = { ...user, accessMode: "ASSIGNED" } as SessionUser;
assert.equal(canTouchRecord(assigned, { ownerId: "staff-b", assignedToId: user.id }), true, "Either scoped assignment grants access");
assert.equal(canTouchRecord(assigned, { ownerId: user.id, assignedToId: "staff-b" }), true);
assert.equal(canTouchRecord(assigned, { ownerId: "staff-b", assignedToId: "staff-c" }), false);
assert.equal(canTouchRecord(assigned, {}), false);
for (const value of ["TRIPJACK_API", " tripjack_api ", "Tripjack_API"]) assert.equal(isReservedBookingSource(value), true);
for (const value of [undefined, null, "", "AMADEUS", "GALILEO"]) assert.equal(isReservedBookingSource(value), false);
const original = new Date("2026-01-01T09:00:00Z"), now = new Date("2026-01-02T10:00:00Z");
assert.equal(taskCompletedAt({ status: "DONE", completedAt: original }, "DONE", now), original);
assert.equal(taskCompletedAt({ status: "OPEN", completedAt: null }, "DONE", now), now);
assert.equal(taskCompletedAt({ status: "DONE", completedAt: original }, "OPEN", now), null);
assert.equal(taskCompletedAt({ status: "DONE", completedAt: original }, "CANCELLED", now), null);
console.log("Workflow regressions passed: branch isolation, assignment parity, reserved booking source and idempotent task completion.");
