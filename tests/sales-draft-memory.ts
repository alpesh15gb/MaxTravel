import assert from "node:assert/strict";
import { createSalesDraftMemory, QUOTE_DRAFT_TTL } from "../src/lib/sales-draft-memory";
let clock = 10;
const store = createSalesDraftMemory("scoped-session-a", () => clock);
const key = { nonce: "entry-a", leadId: "lead-a", baseRevision: "revision-a" };
const fields = { items: [{ description: "Last keystroke!", quantity: 1, priceMinor: 1200, costMinor: 600 }], terms: "Private conditions", expiry: "2030-01-01T10:00" };
let notifications = 0;
const unsubscribe = store.subscribe(() => { notifications++; });
assert.equal(store.retain(key, fields), true);
assert.equal(store.getSnapshot()?.fields?.items[0].description, "Last keystroke!");
fields.items[0].description = "outside mutation";
assert.equal(store.getSnapshot()?.fields?.items[0].description, "Last keystroke!", "Copy is independent of caller-owned fields");
assert.equal(store.retain({ ...key, nonce: "different" }, fields), false, "Never silently replace another draft");
assert.equal(store.beginSubmit(key.nonce), true);
assert.equal(store.getSnapshot()?.phase, "submitting", "Marker written synchronously before fetch");
assert.equal(store.retain(key, fields), false, "Pending draft cannot be rewritten as unsent");
store.settle("old-request", "acknowledged");
assert.equal(store.getSnapshot()?.phase, "submitting", "Late unrelated response cannot erase current entry");
store.settle(key.nonce, "uncertain");
assert.equal(store.getSnapshot()?.phase, "uncertain");
clock += QUOTE_DRAFT_TTL;
store.expire();
assert.equal(store.getSnapshot()?.fields, null, "TTL removes private text");
assert.equal(store.getSnapshot()?.phase, "uncertain", "TTL does not clear unknown-write safety marker");
store.clear();
assert.equal(store.getSnapshot(), null);
assert.equal(store.retain(key, fields), true);
store.settle(key.nonce, "acknowledged");
assert.equal(store.getSnapshot(), null, "Acknowledged save clears copy");
store.retain(key, fields); store.settle(key.nonce, "rejected");
assert.equal(store.getSnapshot()?.phase, "editing", "Known rejection retains editable source");
clock += QUOTE_DRAFT_TTL; store.expire();
assert.equal(store.getSnapshot(), null, "Unused unsent draft expires entirely");
assert.equal(store.retain(key, { ...fields, items: Array.from({ length: 101 }, () => fields.items[0]) }), false);
assert.equal(store.retain(key, { ...fields, terms: "x".repeat(10001) }), false);
assert.equal(store.retain(key, { ...fields, items: [{ ...fields.items[0], quantity: NaN }] }), false);
assert.equal(store.retain(key, { ...fields, items: Array.from({ length: 100 }, () => ({ ...fields.items[0], description: "界".repeat(500) })) }), false, "Byte cap applies to multibyte text, not just character count");
const otherSession = createSalesDraftMemory("scoped-session-b");
assert.equal(otherSession.getSnapshot(), null, "Store is per authenticated layout, never module-global");
assert.equal(createSalesDraftMemory("").retain(key, fields), false, "No identity means no retention");
unsubscribe(); const seen = notifications; store.clear(); assert.equal(notifications, seen);
console.log("Sales draft memory: bounded synchronous copies, nonce outcomes, isolation and TTL PASS");
