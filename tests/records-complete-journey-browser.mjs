// Actual invoice/customer/checklist forms in the disposable review app. No live data or provider activity.
import assert from 'node:assert/strict';
import {runSyntheticJourney} from './synthetic-ui-journey-fixture.mjs';

await runSyntheticJourney('records-complete-journey',3395,async({base,db,fixture,session,capture,postResult,lostResponseRetry,check})=>{
  for(const width of [1440,390]){
    const {page,context}=await session(width);
    const description=`Synthetic standalone invoice ${width}`;
    await page.goto(base+'/payments');
    await page.getByRole('button',{name:'Create invoice',exact:true}).click();
    let dialog=page.getByRole('dialog',{name:'Create an invoice',exact:true});
    await dialog.getByRole('combobox',{name:'01 / Customer *',exact:true}).selectOption(fixture.customerId);
    await dialog.getByRole('combobox',{name:/^02 \/ Link to work/}).selectOption('');
    await dialog.getByLabel('03 / Amount (INR) *',{exact:true}).fill('250.75');
    await dialog.getByLabel('Description',{exact:true}).fill(description);
    await dialog.getByLabel(/^Due date/).fill('2099-11-01');
    const invoiceResult=await lostResponseRetry(page,'/api/invoices',dialog.getByRole('button',{name:'Create invoice',exact:true}),dialog.locator('[role="alert"]:not(#__next-route-announcer__)'));
    assert.equal(invoiceResult.result.invoiceId,invoiceResult.original.invoiceId);
    const invoiceId=invoiceResult.result.invoiceId;
    await dialog.waitFor({state:'hidden'});
    assert.equal(await db.invoice.count({where:{description}}),1,'Lost acknowledgement must not create another invoice');
    const invoice=await db.invoice.findUniqueOrThrow({where:{id:invoiceId}});
    assert.equal(invoice.amount,250.75);assert.equal(invoice.amountPaid,0);assert.equal(invoice.status,'UNPAID');
    assert.equal(invoice.bookingId,null);assert.equal(invoice.visaCaseId,null);
    const charges=await db.financialEntry.findMany({where:{sourceType:'Invoice',sourceId:invoiceId}});
    assert.equal(charges.length,1);assert.equal(charges[0].amountMinor,25075n);
    const invoiceRow=page.locator(`[data-invoice-id="${invoiceId}"]:visible`);
    await invoiceRow.getByRole('button',{name:'Issue credit note',exact:true}).click();
    dialog=page.getByRole('dialog',{name:'Issue a full credit note',exact:true});
    await dialog.getByRole('textbox',{name:'Reason for credit *',exact:true}).fill('Discarded synthetic reason');
    await dialog.getByRole('button',{name:'Cancel',exact:true}).click();
    assert.equal(await db.invoiceCreditNote.count({where:{invoiceId}}),0);
    assert.equal((await db.invoice.findUniqueOrThrow({where:{id:invoiceId}})).status,'UNPAID');
    await invoiceRow.getByRole('button',{name:'Issue credit note',exact:true}).click();
    dialog=page.getByRole('dialog',{name:'Issue a full credit note',exact:true});
    await dialog.getByRole('textbox',{name:'Reason for credit *',exact:true}).fill('bad');
    assert(await dialog.getByRole('button',{name:'Issue credit note',exact:true}).isDisabled());
    await dialog.getByRole('textbox',{name:'Reason for credit *',exact:true}).fill('Synthetic service cancelled before collection');
    // A definitive pre-write failure must retain the reason and leave the invoice uncredited.
    const fail=route=>route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({error:'Synthetic credit service unavailable'})});
    await page.route('**/api/invoices/credit-note',fail);
    await dialog.getByRole('button',{name:'Issue credit note',exact:true}).click();
    await dialog.locator('[role="alert"]:not(#__next-route-announcer__)').waitFor();
    assert.equal(await dialog.getByRole('textbox',{name:'Reason for credit *',exact:true}).inputValue(),'Synthetic service cancelled before collection');
    assert.equal(await db.invoiceCreditNote.count({where:{invoiceId}}),0);
    await page.unroute('**/api/invoices/credit-note',fail);
    const credited=await postResult(page,'/api/invoices/credit-note',()=>dialog.getByRole('button',{name:'Issue credit note',exact:true}).dblclick());
    await dialog.waitFor({state:'hidden'});
    assert.equal(await db.invoiceCreditNote.count({where:{invoiceId}}),1);
    const note=await db.invoiceCreditNote.findUniqueOrThrow({where:{invoiceId}});
    assert.equal(note.id,credited.creditNoteId);assert.equal(note.amount,250.75);
    assert.equal((await db.invoice.findUniqueOrThrow({where:{id:invoiceId}})).status,'CREDITED');
    const credits=await db.financialEntry.findMany({where:{sourceType:'InvoiceCreditNote',sourceId:note.id}});
    assert.equal(credits.length,1);assert.equal(credits[0].amountMinor,-25075n);
    assert.equal(charges[0].amountMinor+credits[0].amountMinor,0n,'Unpaid standalone invoice credit must reconcile to zero, without a cash receipt/refund');
    assert.equal(await db.payment.count({where:{invoiceId}}),0);assert.equal(await db.refund.count({where:{invoiceId}}),0);
    await page.reload();await invoiceRow.getByRole('link',{name:'Credit note',exact:true}).waitFor();
    assert.equal(await invoiceRow.getByRole('button',{name:'Issue credit note',exact:true}).count(),0);
    assert.equal(await invoiceRow.getByRole('button',{name:'Collect',exact:true}).count(),0);
    assert.equal(await invoiceRow.getByRole('link',{name:'Collect',exact:true}).count(),0);
    await capture(page,`invoice-credited-${width}`);
    const creditDocument=await context.newPage();
    await creditDocument.goto(base+await invoiceRow.getByRole('link',{name:'Credit note',exact:true}).getAttribute('href'));
    await creditDocument.getByRole('heading',{name:'Credit note',exact:true}).waitFor();
    await creditDocument.getByText(note.creditNoteNo,{exact:true}).waitFor();
    await creditDocument.getByText('Synthetic service cancelled before collection',{exact:true}).waitFor();
    await capture(creditDocument,`credit-document-${width}`);await creditDocument.close();
    check(`${width}: real standalone invoice lost-response same-ID retry→cancelled credit dialog(no mutation)→short reason disabled→503 retains reason→repeated credit submit→one immutable credit and zero-net journal→reload cannot recollect→actual credit document`);

    // Customer identity and traveller records are edited through the real customer workspace.
    await page.goto(base+`/customers/${fixture.customerId}`);
    const originalCustomer=await db.customer.findUniqueOrThrow({where:{id:fixture.customerId}});
    await page.getByRole('button',{name:'Edit customer',exact:true}).click();
    dialog=page.getByRole('dialog',{name:'Edit customer',exact:true});
    await dialog.getByLabel('City',{exact:true}).fill('Discarded synthetic city');
    await dialog.getByRole('button',{name:'Cancel',exact:true}).click();
    assert.equal((await db.customer.findUniqueOrThrow({where:{id:fixture.customerId}})).city,originalCustomer.city);
    await page.getByRole('button',{name:'Edit customer',exact:true}).click();
    dialog=page.getByRole('dialog',{name:'Edit customer',exact:true});
    await dialog.getByLabel('City',{exact:true}).fill(`Synthetic City ${width}`);
    const customerFailure=route=>route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({error:'Synthetic customer update unavailable'})});
    await page.route(`**/api/customers/${fixture.customerId}`,customerFailure);
    await dialog.getByRole('button',{name:'Save changes',exact:true}).click();await dialog.locator('[role="alert"]:not(#__next-route-announcer__)').waitFor();
    assert.equal(await dialog.getByLabel('City',{exact:true}).inputValue(),`Synthetic City ${width}`);
    assert.equal((await db.customer.findUniqueOrThrow({where:{id:fixture.customerId}})).city,originalCustomer.city);
    await page.unroute(`**/api/customers/${fixture.customerId}`,customerFailure);
    await postResult(page,`/api/customers/${fixture.customerId}`,()=>dialog.getByRole('button',{name:'Save changes',exact:true}).click());
    await dialog.waitFor({state:'hidden'});await page.reload();
    assert.equal((await db.customer.findUniqueOrThrow({where:{id:fixture.customerId}})).city,`Synthetic City ${width}`);
    await page.goto(base+`/customers/${fixture.customerId}?tab=travellers`);
    await page.getByRole('button',{name:'+ Add Traveller',exact:true}).click();
    dialog=page.getByRole('dialog',{name:'Add traveller',exact:true});
    const travellerName=`Synthetic Traveller ${width}`;
    await dialog.getByLabel('Full name *',{exact:true}).fill(travellerName);
    await dialog.getByRole('combobox',{name:'Relationship to customer',exact:true}).selectOption('GROUP');
    await dialog.getByLabel('Date of birth',{exact:true}).fill('1990-01-01');
    await dialog.getByRole('combobox',{name:'Gender',exact:true}).selectOption('OTHER');
    await dialog.getByLabel('Passport number',{exact:true}).fill(`QA${width}SYNTHETIC`);
    await dialog.getByLabel('Place of issue',{exact:true}).fill('Synthetic test location');
    await dialog.getByLabel('Passport issue date',{exact:true}).fill('2020-01-01');
    await dialog.getByLabel('Passport expiry',{exact:true}).fill('2000-01-01');
    await dialog.getByRole('button',{name:'Add',exact:true}).click();await dialog.locator('[role="alert"]:not(#__next-route-announcer__)').waitFor();
    assert.equal(await db.traveller.count({where:{fullName:travellerName}}),0,'Rejected expired passport must leave no partial traveller');
    assert.equal(await dialog.getByLabel('Full name *',{exact:true}).inputValue(),travellerName);
    await dialog.getByLabel('Passport expiry',{exact:true}).fill('2099-01-01');
    const addedTraveller=await postResult(page,'/api/travellers',()=>dialog.getByRole('button',{name:'Add',exact:true}).click());
    await dialog.waitFor({state:'hidden'});
    const traveller=await db.traveller.findUniqueOrThrow({where:{id:addedTraveller.travellerId}});
    assert.equal(traveller.customerId,fixture.customerId);assert.equal(traveller.relation,'GROUP');
    assert.equal(traveller.passportExpiry.toISOString(),'2099-01-01T00:00:00.000Z');
    const travellerPanel=page.locator('section.panel').filter({has:page.getByText(travellerName,{exact:true})});
    await travellerPanel.getByRole('button',{name:'Edit',exact:true}).click();
    dialog=page.getByRole('dialog',{name:`Edit ${travellerName}`,exact:true});
    await dialog.getByLabel('Frequent flyer',{exact:true}).fill('Discarded synthetic membership');
    await dialog.getByRole('button',{name:'Cancel',exact:true}).click();
    assert.equal((await db.traveller.findUniqueOrThrow({where:{id:traveller.id}})).frequentFlyer,null);
    await travellerPanel.getByRole('button',{name:'Edit',exact:true}).click();
    dialog=page.getByRole('dialog',{name:`Edit ${travellerName}`,exact:true});
    await dialog.getByLabel('Frequent flyer',{exact:true}).fill(`SYNTHETIC-${width}`);
    await postResult(page,`/api/travellers/${traveller.id}`,()=>dialog.getByRole('button',{name:'Save',exact:true}).click());
    await dialog.waitFor({state:'hidden'});await page.reload();
    assert.equal((await db.traveller.findUniqueOrThrow({where:{id:traveller.id}})).frequentFlyer,`SYNTHETIC-${width}`);
    assert.equal(await db.traveller.count({where:{fullName:travellerName}}),1);
    await travellerPanel.getByText(`SYNTHETIC-${width}`,{exact:true}).waitFor();await capture(page,`traveller-edited-${width}`);
    check(`${width}: customer edit cancel→503 retained fields→save/reload; add traveller expired-passport rejection(no partial row)→correct expiry→edit cancel→save→reload with same traveller identity`);

    const destination=`Synthetic Destination ${width}`,visaType='Synthetic visitor';
    async function checklist(version,invalid=false){
      await page.goto(base+'/checklists');await page.getByRole('button',{name:'New checklist version',exact:true}).click();
      const form=page.getByRole('dialog',{name:'New checklist',exact:true});
      await form.getByLabel('Country *',{exact:true}).fill(destination);await form.getByLabel('Visa type *',{exact:true}).fill(visaType);
      await form.getByRole('combobox',{name:'Applicant type',exact:true}).selectOption('STANDARD');
      await form.getByLabel('Document name *',{exact:true}).fill(`Synthetic requirement v${version}`);
      await form.getByLabel('Allowed file types',{exact:true}).fill(invalid?'exe':'pdf');
      await form.getByLabel('Client instructions',{exact:true}).fill('Synthetic test requirement, not real immigration advice.');
      if(invalid){
        await form.getByRole('button',{name:'Save checklist version',exact:true}).click();await form.locator('[role="alert"]:not(#__next-route-announcer__)').waitFor();
        assert.equal(await db.checklist.count({where:{country:destination,visaType}}),1);
        assert.equal((await db.checklist.findFirstOrThrow({where:{country:destination,visaType,version:1}})).active,true,'Invalid replacement must not deactivate existing master');
        assert.equal(await form.getByLabel('Document name *',{exact:true}).inputValue(),`Synthetic requirement v${version}`);
        await form.getByLabel('Allowed file types',{exact:true}).fill('pdf');
      }
      const saved=await postResult(page,'/api/checklists',()=>form.getByRole('button',{name:'Save checklist version',exact:true}).click());await form.waitFor({state:'hidden'});return saved.checklist;
    }
    const first=await checklist(1);assert.equal(first.version,1);
    await page.goto(base+`/visa/new?customer=${fixture.customerId}`);
    await page.getByRole('checkbox',{name:new RegExp(`^${travellerName}\\s+group$`)}).check();
    await page.getByLabel('Destination country *',{exact:true}).fill(destination);await page.getByLabel('Visa type *',{exact:true}).fill(visaType);
    await page.getByRole('combobox',{name:/^Checklist/}).selectOption(first.id);
    await page.getByLabel('Travel date',{exact:true}).fill('2098-01-01');
    await page.getByLabel('Visa fee (INR)',{exact:true}).fill('80.25');await page.getByLabel('Service fee (INR)',{exact:true}).fill('20.25');
    const createdCase=await postResult(page,'/api/visa/cases',()=>page.getByRole('button',{name:'Create visa case',exact:true}).click());
    await page.waitForURL(`**/visa/${createdCase.caseId}`);
    const caseRecord=await db.visaCase.findUniqueOrThrow({where:{id:createdCase.caseId}});assert.equal(caseRecord.sellingPrice,100.5);
    const initialDocuments=await db.document.findMany({where:{visaCaseId:caseRecord.id}});assert.equal(initialDocuments.length,1);assert.equal(initialDocuments[0].travellerId,traveller.id);assert.equal(initialDocuments[0].docType,'Synthetic requirement v1');
    assert.equal(await db.caseTraveller.count({where:{caseId:caseRecord.id,travellerId:traveller.id}}),1);
    const second=await checklist(2,true);assert.equal(second.version,2);assert.equal(second.active,true);
    assert.equal((await db.checklist.findUniqueOrThrow({where:{id:first.id}})).active,false);
    const links=await db.checklistLink.findMany({where:{caseId:caseRecord.id}});assert.equal(links.length,1);assert.equal(links[0].checklistId,first.id);
    const retainedDocuments=await db.document.findMany({where:{visaCaseId:caseRecord.id}});assert.deepEqual(retainedDocuments.map(d=>d.id),initialDocuments.map(d=>d.id));assert.equal(retainedDocuments[0].docType,'Synthetic requirement v1');
    await page.goto(base+`/visa/${caseRecord.id}`);await page.getByText('Synthetic requirement v1',{exact:true}).first().waitFor();
    await page.getByRole('link',{name:'All visa cases',exact:true}).click();await page.waitForURL('**/visa');
    await page.goBack();await page.waitForURL(`**/visa/${caseRecord.id}`);await page.reload();
    await page.getByText('Synthetic requirement v1',{exact:true}).first().waitFor();
    assert.equal(await db.visaCase.count({where:{id:caseRecord.id}}),1);
    assert.equal(await db.document.count({where:{visaCaseId:caseRecord.id}}),1);
    await capture(page,`visa-version-preserved-${width}`);
    check(`${width}: real checklist v1→new visa case with exact traveller and100.50 charge→invalid replacement leaves v1 active→valid v2 supersedes master but original dossier link/document identities stay v1 across Back/reload`);
    await context.close();
  }
});
